#!/usr/bin/env python3
"""Build Familiar Characters: static pages, images, and share cards.

Content lives in _familiar-characters/ (not published): one text file per
Character in characters/, original images in images/, and the index settings
in collection.md. This script turns it into:

  familiar-characters/index.html               the index: the grid, the House, and
                                               the overlay each Character opens in
  familiar-characters/NNN-slug/index.html      each Character on its own: the same
                                               overlay, as a page (shareable, indexable)
  img/characters/*.webp                        resized images, 480 to 1800 px wide,
                                               and red-tinted ones for the House
  img/characters/share/*.jpg                   1200 × 630 share images
  sitemap.xml                                  published Characters only

    python3 scripts/build_characters.py           build
    python3 scripts/build_characters.py --check   check the content, write nothing

Needs Python 3.9+ and Pillow (python3 -m pip install Pillow). The pages link to
the site's own css/ and js/, and take the footer from index.html, so the two
stay the same.
"""
