class BuildError(Exception):
    pass


@dataclass
class Picture:
    file: str
    alt: str
    credit: str
    width: int = 0
    height: int = 0
    color: str | None = None      # average colour, shown while the image loads
    digest: str = ''
    variants: list = field(default_factory=list)   # [(width, file name)]
    tints: list = field(default_factory=list)      # the same, tinted red for the House

    @property
    def ratio(self) -> float:
        return self.width / self.height


@dataclass
class Character:
    number: str
    slug: str                      # "012-clear-water-bottle": file, folder, and URL
    path: Path
    title: str
    maker: str
    designer: str
    designer_label: str
    year: str
    category: str
    country: str
    material: str
    dimensions: str
    kind: str
    tags: list
    source: str
    added: date | None
    placeholder: bool
    summary: str
    note: list                     # paragraphs, as written
    picture: Picture
    share: str = ''

    @property
    def url(self) -> str:
        return f'{INDEX_URL}{self.slug}/'


# Text -------------------------------------------------------------------------

def rel(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def esc(text: str) -> str:
    return html.escape(text, quote=True)


def smart(text: str) -> str:
    """Typographer's quotes and apostrophes, as in the rest of the site."""
    text = re.sub(r"(?<=\w)'(?=\w)", '’', text)
    text = re.sub(r"'(?=\d\ds\b)", '’', text)
    text = re.sub(r"(^|[\s(\[—–-])'", r'\1‘', text)
    text = text.replace("'", '’')
    text = re.sub(r'(^|[\s(\[‘—–-])"', r'\1“', text)
    return text.replace('"', '”')


LINK_RE = re.compile(r'\[([^\]]+)\]\((https?://[^\s)]+|/[^\s)]*)\)')


def inline(text: str, root: str) -> str:
    """One paragraph of a note: escaped, with [text](url) links."""
    out, last = [], 0
    for m in LINK_RE.finditer(text):
        out.append(esc(smart(text[last:m.start()])))
        url, label = m.group(2), esc(smart(m.group(1)))
        if url.startswith('/'):
            out.append(f'<a href="{esc(root + url[1:])}">{label}</a>')
        else:
            out.append(f'<a href="{esc(url)}" target="_blank" rel="noopener noreferrer">{label}<span class="sr-only"> (opens in a new tab)</span></a>')
        last = m.end()
    out.append(esc(smart(text[last:])))
    return ''.join(out)


def plain(text: str) -> str:
    return smart(LINK_RE.sub(r'\1', text))


def first_sentence(text: str) -> str:
    m = re.match(r'(.+?[.!?])(?:\s|$)', text)
    return m.group(1) if m else text


def clip(text: str, limit: int) -> str:
    if len(text) <= limit:
        return text
    return text[:limit - 1].rsplit(' ', 1)[0].rstrip(',;:') + '…'


def split_list(value: str) -> list:
    return [v.strip() for v in value.split(',') if v.strip()]


def paragraphs(body: str) -> list:
    blocks = re.split(r'\n[ \t]*\n', body.strip())
    return [' '.join(line.strip() for line in b.split('\n')) for b in blocks if b.strip()]


def month(d: date) -> str:
    return f'{MONTHS[d.month - 1]} {d.year}'


def credit(c: Character) -> str:
    """“Designer for Maker, 2022”, or as much of it as is known."""
    if c.designer and c.maker:
        who = f'{c.designer} for {c.maker}' if c.designer_label == 'Designed by' else f'{c.designer}, {c.maker}'
    else:
        who = c.designer or c.maker
    return ', '.join(x for x in (who, c.year) if x)


def token(text: str) -> str:
    return re.sub(r'[^a-z0-9]+', '-', text.lower()).strip('-')


# Reading content ----------------------------------------------------------------

def read(path: Path):
    """Settings between two lines of ---, then the text."""
    text = path.read_text(encoding='utf-8').replace('\r\n', '\n')
    m = re.match(r'---[ \t]*\n(.*?)\n---[ \t]*(?:\n|$)(.*)', text, re.S)
    if not m:
        raise BuildError(f'{rel(path)}: must begin with its settings between two lines of ---')
    meta, images = {}, []
    for n, line in enumerate(m.group(1).split('\n'), 2):
        s = line.strip()
        if not s or s.startswith('#'):
            continue
        key, sep, value = s.partition(':')
        key = key.strip().lower()
        if not sep or not re.fullmatch(r'[a-z][a-z0-9-]*', key):
            raise BuildError(f'{rel(path)}, line {n}: expected “key: value”, found “{s}”')
        if key == 'image':
            images.append((value.strip(), n))
        elif key in meta:
            raise BuildError(f'{rel(path)}, line {n}: “{key}” is set twice')
        else:
            meta[key] = value.strip()
    return meta, images, m.group(2)


def load_settings(errors: list) -> dict:
    path = SRC / 'collection.md'
    try:
        meta, _, body = read(path)
    except (BuildError, OSError) as e:
        errors.append(str(e))
        return {}
    s = {
        'title': meta.get('title') or 'Familiar Characters',
        'description': meta.get('description', ''),
        'order': meta.get('order', 'newest'),
        'filters': meta.get('filters', 'off'),
        'essay_url': meta.get('essay-url', ''),
        'essay_link': meta.get('essay-link') or 'About Familiar Characters',
        'essay_kicker': meta.get('essay-kicker') or 'From the House',
        'essay_title': meta.get('essay-title', ''),
        'end_note': meta.get('end-note', ''),
        'categories': split_list(meta.get('categories', '')),
        'tags': [t.lower() for t in split_list(meta.get('tags', ''))],
        'intro': paragraphs(body),
    }
    if s['order'] not in ('newest', 'oldest'):
        errors.append(f'{rel(path)}: order is “newest” or “oldest”')
    if s['filters'] not in ('off', 'category'):
        errors.append(f'{rel(path)}: filters is “off” or “category”')
    if not s['categories']:
        errors.append(f'{rel(path)}: list the categories, e.g. “categories: Home, Kitchen, Desk”')
    if s['essay_url'] and not re.match(r'(https?://|/)', s['essay_url']):
        errors.append(f'{rel(path)}: essay-url is a full address (https://…) or a path on this site (/…)')
    return s


def load_characters(settings: dict, errors: list, warnings: list) -> list:
    chars, numbers = [], {}
    categories = {c.lower(): c for c in settings.get('categories', [])}
    for path in sorted((SRC / 'characters').glob('*.md')):
        if path.name.startswith('_'):
            continue
        where = rel(path)
        m = FILE_RE.match(path.name)
        if not m:
            errors.append(f'{where}: name the file with its number and a short name, like 013-folding-chair.md')
            continue
        number = m.group(1)
        if int(number) in numbers:
            errors.append(f'{where}: No. {number} is already used by {numbers[int(number)]}')
            continue
        numbers[int(number)] = rel(path)
        try:
            meta, images, body = read(path)
        except (BuildError, OSError) as e:
            errors.append(str(e))
            continue
        problems = []
        for key in meta.keys() - FIELDS:
            problems.append(f'unknown setting “{key}” (a typo?)')
        if meta.get('number') and meta['number'] != number:
            problems.append(f'number {meta["number"]} does not match the file name ({number})')
        title = meta.get('title', '')
        if not title:
            problems.append('needs a title')
        category = categories.get(meta.get('category', '').lower())
        if not category:
            problems.append(f'category is one of: {", ".join(settings.get("categories", []))} (add new ones in collection.md)')
        kind = meta.get('kind', 'found').lower()
        if kind not in KINDS:
            problems.append('kind is found, made-with, or made-by-2d1')
        tags = [t.lower() for t in split_list(meta.get('tags', ''))]
        unknown = [t for t in tags if settings.get('tags') and t not in settings['tags']]
        if unknown:
            warnings.append(f'{where}: tag{"s" if len(unknown) > 1 else ""} not in collection.md: {", ".join(unknown)}')
        source = meta.get('source', '')
        if source and not re.match(r'https?://', source):
            problems.append('source is a full address, starting with https://')
        added = None
        if meta.get('added'):
            try:
                added = date.fromisoformat(meta['added'])
            except ValueError:
                problems.append('added is a date like 2026-09-29')
        placeholder = meta.get('placeholder', 'no').lower()
        if placeholder not in ('yes', 'no', 'true', 'false'):
            problems.append('placeholder is yes or no')
        note = paragraphs(body)
        if not note:
            problems.append('needs a note (the text under the second ---)')
        picture = None
        if not images:
            problems.append('needs an image')
        else:
            value, line = images[0]
            parts = [p.strip() for p in value.split('|')]
            if len(parts) < 2 or not parts[0] or not parts[1]:
                problems.append(f'line {line}: image is “file | alt text | credit” (alt text is required)')
            elif not (SRC / 'images' / parts[0]).is_file():
                problems.append(f'line {line}: no file _familiar-characters/images/{parts[0]}')
            else:
                picture = Picture(parts[0], parts[1], parts[2] if len(parts) > 2 else '')
            if len(images) > 1:
                warnings.append(f'{where}: one image per Character; using the first ({parts[0]})')
        if problems:
            errors.extend(f'{where}: {p}' for p in problems)
            continue
        chars.append(Character(
            number=number, slug=path.stem, path=path, title=smart(title),
            maker=smart(meta.get('maker', '')), designer=smart(meta.get('designer', '')),
            designer_label=meta.get('designer-label') or 'Designed by', year=meta.get('year', ''),
            category=category, country=smart(meta.get('country', '')), material=smart(meta.get('material', '')),
            dimensions=smart(meta.get('dimensions', '')), kind=kind, tags=tags, source=source, added=added,
            placeholder=placeholder in ('yes', 'true'),
            summary=smart(meta['summary']) if meta.get('summary') else first_sentence(plain(note[0])),
            note=note, picture=picture,
        ))
    return chars


# Images ---------------------------------------------------------------------------

def variant_widths(width: int) -> list:
    return sorted({w for w in WIDTHS if w < width} | {min(width, WIDTHS[-1])})


def tint(im: Image.Image) -> Image.Image:
    """The House's duotone: shadows go to ink, light goes to Icon Red, one red only."""
    lut = []
    for channel in range(3):
        for i in range(256):
            t = (i / 255) ** TINT_GAMMA
            lut.append(round(INK[channel] + (RED[channel] - INK[channel]) * t))
    gray = ImageOps.autocontrast(ImageOps.grayscale(im.convert('RGB')), cutoff=TINT_CUTOFF)
    out = gray.convert('RGB').point(lut)
    if im.mode == 'RGBA':
        out.putalpha(im.getchannel('A'))
    return out


def prepare(pic: Picture, c: Character, cache: dict, produced: set) -> None:
    """Resize the original into WebP variants and tinted ones, once; remember its size and colour."""
    path = SRC / 'images' / pic.file
    data = path.read_bytes()
    pic.digest = hashlib.sha1(data + IMAGE_VERSION.encode()).hexdigest()[:10]
    tint_digest = hashlib.sha1(data + (IMAGE_VERSION + TINT_VERSION).encode()).hexdigest()[:10]

    def names():
        pic.variants = [(w, f'{c.slug}-{w}.{pic.digest}.webp') for w in variant_widths(pic.width)]
        pic.tints = [(w, f'{c.slug}-tint-{w}.{tint_digest}.webp') for w in sorted({min(w, pic.width) for w in TINT_WIDTHS})]

    known = cache.get(pic.digest)
    if known:
        pic.width, pic.height, pic.color = known['w'], known['h'], known.get('color')
        names()
        if all((IMG / name).exists() for _, name in pic.variants + pic.tints):
            produced.update(name for _, name in pic.variants + pic.tints)
            return
    with Image.open(path) as original:
        icc = original.info.get('icc_profile')
        im = ImageOps.exif_transpose(original)
        alpha = im.mode in ('RGBA', 'LA', 'PA') or 'transparency' in im.info
        im = im.convert('RGBA' if alpha else 'RGB')
    pic.width, pic.height = im.size
    pic.color = None if alpha else '#%02x%02x%02x' % im.resize((1, 1), Image.Resampling.BOX).getpixel((0, 0))[:3]
    cache[pic.digest] = {'w': pic.width, 'h': pic.height, 'color': pic.color}
    names()
    red = None
    for (w, name), tinted in [(v, False) for v in pic.variants] + [(v, True) for v in pic.tints]:
        produced.add(name)
        out = IMG / name
        if out.exists():
            continue
        source = im
        if tinted:
            red = red or tint(im)
            source = red
        frame = source if w == pic.width else source.resize((w, max(1, round(pic.height * w / pic.width))), Image.Resampling.LANCZOS)
        options = {'quality': 80, 'method': 6}   # no EXIF is copied: phone photos keep their location to themselves
        if icc and not tinted:
            options['icc_profile'] = icc
        if alpha:
            options['alpha_quality'] = 90
        frame.save(out, 'WEBP', **options)


def srcset(pic: Picture, root: str, limit: int = WIDTHS[-1], tinted: bool = False) -> str:
    return ', '.join(f'{root}img/characters/{name} {w}w' for w, name in (pic.tints if tinted else pic.variants) if w <= limit)


def fallback(pic: Picture, root: str, limit: int) -> str:
    fits = [name for w, name in pic.variants if w <= limit]
    return f'{root}img/characters/{fits[-1]}'


def card_sizes(pic: Picture) -> str:
    # Narrow images don't fill their box, so ask for less.
    factor = min(1.0, pic.ratio / CELL)
    parts = []
    for min_width, width in GRID:
        size = f'calc({width})' if factor > .97 else f'calc(({width}) * {factor:.2f})'
        parts.append(f'(min-width: {min_width}px) {size}' if min_width else size)
    return ', '.join(parts)


def picture_style(pic: Picture) -> str:
    return f'--r:{pic.ratio:.4f}' + (f';background-color:{pic.color}' if pic.color else '')


