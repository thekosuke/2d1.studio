def write(path: Path, text: str) -> bool:
    if path.exists() and path.read_text(encoding='utf-8') == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding='utf-8')
    return True


def update_sitemap(chars: list, placeholders: bool) -> None:
    path = ROOT / 'sitemap.xml'
    text = path.read_text(encoding='utf-8')
    urls = [] if placeholders else [(INDEX_URL, None)]   # the index waits until every placeholder is gone
    urls += [(c.url, c.added) for c in chars if not c.placeholder]
    start, end = '<!-- familiar-characters -->', '<!-- /familiar-characters -->'
    block = start + ''.join(f'<url><loc>{u}</loc>{f"<lastmod>{d.isoformat()}</lastmod>" if d else ""}</url>' for u, d in urls) + end
    if start in text:
        text = re.sub(re.escape(start) + '.*?' + re.escape(end), block, text, flags=re.S)
    elif urls:
        text = text.replace('</urlset>', block + '</urlset>')
    else:
        return
    write(path, text)


def clean(slugs: set, images: set, shares: set) -> list:
    removed = []
    for f in IMG.glob('*.webp'):
        if f.name not in images:
            f.unlink()
            removed.append(rel(f))
    for f in SHARE.glob('*.jpg'):
        if f.name not in shares:
            f.unlink()
            removed.append(rel(f))
    if OUT.is_dir():
        for d in OUT.iterdir():
            page = d / 'index.html'
            if d.is_dir() and d.name not in slugs and page.is_file() and MARK in page.read_text(encoding='utf-8'):
                page.unlink()
                removed.append(rel(page))
                try:
                    d.rmdir()
                except OSError:
                    pass
    return removed


def from_home() -> tuple:
    home = (ROOT / 'index.html').read_text(encoding='utf-8')
    footer = re.search(r'<footer class="footer">.*?</footer>', home, re.S)
    mark = re.search(r'<svg class="logo-mark".*?</svg>', home, re.S)
    if not footer or not mark:
        raise BuildError('index.html: could not find the footer (<footer class="footer">) or the logo (<svg class="logo-mark">)')
    footer = re.sub(r'\n {6}', '\n  ', footer.group(0))
    return footer, mark.group(0)


def main() -> None:
    parser = argparse.ArgumentParser(description='Build the Familiar Characters pages from _familiar-characters/.')
    parser.add_argument('--check', action='store_true', help='check the content without writing anything')
    args = parser.parse_args()

    errors, warnings = [], []
    settings = load_settings(errors)
    chars = load_characters(settings, errors, warnings) if settings else []
    if not errors and not chars:
        errors.append('_familiar-characters/characters/ has no Characters yet')
    for w in warnings:
        print(f'  note: {w}')
    if errors:
        print('Familiar Characters: nothing was built.\n' + '\n'.join(f'  ✕ {e}' for e in errors), file=sys.stderr)
        sys.exit(1)
    placeholders = [c for c in chars if c.placeholder]
    if args.check:
        print(f'Familiar Characters: {len(chars)} Characters check out ({len(placeholders)} placeholders).')
        return

    try:
        footer, logo_svg = from_home()
    except BuildError as e:
        sys.exit(f'Familiar Characters: {e}')
    cache = json.loads(CACHE.read_text()) if CACHE.exists() else {}
    IMG.mkdir(parents=True, exist_ok=True)
    SHARE.mkdir(parents=True, exist_ok=True)
    images, shares = set(), set()
    for c in chars:
        try:
            prepare(c.picture, c, cache, images)
        except OSError as e:
            errors.append(f'{rel(c.path)}: could not read {c.picture.file} ({e})')
    if errors:
        print('Familiar Characters: nothing was built.\n' + '\n'.join(f'  ✕ {e}' for e in errors), file=sys.stderr)
        sys.exit(1)
    CACHE.write_text(json.dumps(cache, indent=1, sort_keys=True))

    chars.sort(key=lambda c: int(c.number), reverse=settings['order'] == 'newest')
    fonts = {'mono18': ImageFont.truetype(str(MONO), 18), 'mono20': ImageFont.truetype(str(MONO), 20),
             'mono22': ImageFont.truetype(str(MONO), 22), 'sans26': ImageFont.truetype(str(FONT), 26),
             'sans28': ImageFont.truetype(str(FONT), 28)}
    for c in chars:
        share_character(c, fonts, shares)
    collection_share = share_collection(chars, settings, fonts, shares)

    changed = write(OUT / 'index.html', index_page(chars, settings, collection_share, footer, logo_svg))
    for i, c in enumerate(chars):   # previous and next follow the index's order
        before = chars[i - 1] if i > 0 else None
        after = chars[i + 1] if i + 1 < len(chars) else None
        changed |= write(OUT / c.slug / 'index.html', sheet_page(c, before, after, logo_svg))
    removed = clean({c.slug for c in chars}, images, shares)
    update_sitemap(chars, bool(placeholders))

    print(f'Familiar Characters: {len(chars)} Character{"" if len(chars) == 1 else "s"} → familiar-characters/ ({"updated" if changed else "no page changes"}).')
    if removed:
        print(f'  removed {len(removed)} file{"" if len(removed) == 1 else "s"} no longer used' + (': ' + ', '.join(removed) if len(removed) <= 6 else ''))
    if placeholders:
        print(f'  {len(placeholders)} placeholder{"s" if len(placeholders) > 1 else ""} (noindex, not in the sitemap): '
              + ', '.join(c.number for c in sorted(placeholders, key=lambda c: c.number)))


if __name__ == '__main__':
    main()
