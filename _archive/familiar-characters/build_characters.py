def svg_polygons(d: str, steps: int = 24) -> list:
    tokens = re.findall(r'[MLHVCZ]|-?(?:\d+\.?\d*|\.\d+)', d)
    polys, points, i, cmd, x, y = [], [], 0, '', 0.0, 0.0

    def num() -> float:
        nonlocal i
        i += 1
        return float(tokens[i - 1])

    while i < len(tokens):
        if tokens[i].isalpha():
            cmd = tokens[i]
            i += 1
        if cmd == 'M':
            x, y = num(), num()
            points, cmd = [(x, y)], 'L'
        elif cmd == 'L':
            x, y = num(), num()
            points.append((x, y))
        elif cmd == 'H':
            x = num()
            points.append((x, y))
        elif cmd == 'V':
            y = num()
            points.append((x, y))
        elif cmd == 'C':
            x1, y1, x2, y2, x3, y3 = [num() for _ in range(6)]
            for s in range(1, steps + 1):
                t = s / steps
                u = 1 - t
                points.append((u ** 3 * x + 3 * u * u * t * x1 + 3 * u * t * t * x2 + t ** 3 * x3,
                               u ** 3 * y + 3 * u * u * t * y1 + 3 * u * t * t * y2 + t ** 3 * y3))
            x, y = x3, y3
        elif cmd == 'Z':
            polys.append(points)
            points = []
    return polys


LOGO = [p for d in LOGO_PATHS for p in svg_polygons(d)]


def logo(width: int, color: tuple) -> Image.Image:
    height = round(width * 280 / 775)
    scale = width * 4 / 775
    mask = Image.new('L', (width * 4, height * 4), 0)
    draw = ImageDraw.Draw(mask)
    for poly in LOGO:
        draw.polygon([(px * scale, py * scale) for px, py in poly], fill=255)
    out = Image.new('RGBA', (width, height), color + (0,))
    out.putalpha(mask.resize((width, height), Image.Resampling.LANCZOS))
    return out


def text_width(text: str, font, tracking: float = 0) -> float:
    return font.getlength(text) + tracking * max(len(text) - 1, 0)


def draw_text(draw, x: float, y: float, text: str, font, fill, tracking: float = 0) -> float:
    """Draw text with its baseline at y; tracking is extra space between letters, in px."""
    if not tracking:
        draw.text((x, y), text, font=font, fill=fill, anchor='ls')
    else:
        for i, ch in enumerate(text):
            draw.text((x + font.getlength(text[:i]) + tracking * i, y), ch, font=font, fill=fill, anchor='ls')
    return x + text_width(text, font, tracking)


def wrap(text: str, font, width: float, tracking: float = 0) -> list:
    lines, line = [], ''
    for word in text.split():
        test = f'{line} {word}'.strip()
        if line and text_width(test, font, tracking) > width:
            lines.append(line)
            line = word
        else:
            line = test
    return lines + [line] if line else lines


def shelve(canvas: Image.Image, pic: Picture, box: tuple, right: bool = False) -> None:
    """Fit a picture into box without cropping, standing on its bottom-left (or bottom-right) corner."""
    x0, y0, x1, y1 = box
    with Image.open(SRC / 'images' / pic.file) as original:
        im = ImageOps.exif_transpose(original).convert('RGBA')
    scale = min((x1 - x0) / im.width, (y1 - y0) / im.height)
    im = im.resize((max(1, round(im.width * scale)), max(1, round(im.height * scale))), Image.Resampling.LANCZOS)
    canvas.paste(im, (x1 - im.width if right else x0, y1 - im.height), im)


def share_base(fonts: dict) -> Image.Image:
    """White card with the site's red bar: the active nav item on the left, the logo in the middle."""
    card = Image.new('RGB', (1200, 630), WHITE)
    draw = ImageDraw.Draw(card)
    draw.rectangle((0, 0, 1199, 83), fill=RED)
    draw.rectangle((48, 37, 56, 45), fill=WHITE)
    draw_text(draw, 68, 48, 'FAMILIAR CHARACTERS', fonts['mono18'], WHITE, 0.9)
    mark = logo(104, WHITE)
    card.paste(mark, ((1200 - mark.width) // 2, (84 - mark.height) // 2), mark)
    return card


def share_character(c: Character, fonts: dict, produced: set) -> None:
    lines = [c.number, c.title, c.maker, c.designer, c.designer_label, c.category, c.year, c.picture.digest]
    digest = hashlib.sha1('\n'.join([SHARE_VERSION] + lines).encode()).hexdigest()[:10]
    c.share = f'{c.slug}.{digest}.jpg'
    produced.add(c.share)
    if (SHARE / c.share).exists():
        return
    card = share_base(fonts)
    draw = ImageDraw.Draw(card)
    shelve(card, c.picture, (48, 132, 600, 582), right=True)   # against the text
    x, width = 648, 504
    draw_text(draw, x, 150, f'NO. {c.number}', fonts['mono22'], INK_SOFT, 1.1)
    for size in (58, 50, 44, 38):
        font = ImageFont.truetype(str(FONT), size)
        title = wrap(c.title, font, width, -.03 * size)
        if len(title) <= 4:
            break
    y = 150 + 26 + round(size * .8)
    for line in title:
        draw_text(draw, x, y, line, font, INK, -.03 * size)
        y += round(size * 1.04)
    y += 18
    for text, color in ((c.maker, INK), (f'{c.designer_label} {c.designer}' if c.designer else '', INK_SOFT)):
        for line in wrap(text, fonts['sans28'], width, -.3)[:2]:
            draw_text(draw, x, y, line, fonts['sans28'], color, -.3)
            y += 36
    meta = ' / '.join(v for v in (c.category, c.year) if v).upper()
    draw_text(draw, x, 582, meta, fonts['mono20'], INK_SOFT, 1)
    card.save(SHARE / c.share, 'JPEG', quality=86, optimize=True, progressive=True)


def share_collection(chars: list, settings: dict, fonts: dict, produced: set) -> str:
    shelf = [c.picture for c in chars[:5]]
    intro = plain(settings['intro'][0]) if settings['intro'] else ''
    digest = hashlib.sha1('\n'.join([SHARE_VERSION, settings['title'], intro] + [p.digest for p in shelf]).encode()).hexdigest()[:10]
    name = f'familiar-characters.{digest}.jpg'
    produced.add(name)
    if (SHARE / name).exists():
        return name
    card = share_base(fonts)
    draw = ImageDraw.Draw(card)
    title_font = ImageFont.truetype(str(FONT), 84)
    end = draw_text(draw, 44, 206, settings['title'], title_font, INK, -.045 * 84)
    draw_text(draw, end - .045 * 84, 206, '.', title_font, RED)
    y = 252
    for line in wrap(intro, fonts['sans26'], 620, -.2)[:2]:
        draw_text(draw, 48, y, line, fonts['sans26'], INK_SOFT, -.2)
        y += 34
    for i, pic in enumerate(shelf):
        x = 48 + i * (184 + 24)
        shelve(card, pic, (x, 352, x + 184, 582))
    card.save(SHARE / name, 'JPEG', quality=86, optimize=True, progressive=True)
    return name


