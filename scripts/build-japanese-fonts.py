"""Split the existing OFL Japanese faces without changing glyphs or typography.

Development helper: requires fontTools and Brotli. Generated WOFF2s/CSS are
committed assets; previews and deployment do not need Python font dependencies.
Regenerate Japanese pages first so static and dynamic translations are current.
"""
from copy import deepcopy
from hashlib import sha256
from html.parser import HTMLParser
from pathlib import Path
import json
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'fonts/Zen Kaku Gothic New'
OUTPUT = ROOT / 'fonts/zen-kaku-subsets'

class CanvasText(HTMLParser):
    def __init__(self):
        super().__init__()
        self.stack = []
        self.text = []
    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        skip = bool(self.stack and self.stack[-1][1]) or tag in {'script', 'style', 'template'} or a.get('id') in {'objects-collection', 'objects-about-dialog'} or 'objects-intro' in a.get('class', '').split()
        if tag not in {'area','base','br','col','embed','hr','img','input','link','meta','param','source','track','wbr'}:
            self.stack.append((tag, skip))
        if not skip:
            self.text.extend(a.get(k, '') for k in ('placeholder', 'alt'))
    def handle_endtag(self, tag):
        for i in range(len(self.stack)-1, -1, -1):
            if self.stack[i][0] == tag:
                del self.stack[i:]
                break
    def handle_data(self, data):
        if not self.stack or not self.stack[-1][1]:
            self.text.append(data)

def ranges(points):
    groups = []
    for point in sorted(points):
        if groups and point == groups[-1][1] + 1:
            groups[-1][1] = point
        else:
            groups.append([point, point])
    return ','.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a,b in groups)

translations = json.loads((ROOT / 'locales/ja.json').read_text())
parser = CanvasText()
parser.feed((ROOT / 'ja/familiarcharacters/index.html').read_text())
runtime = '\n'.join((ROOT / 'js' / name).read_text() for name in ('objects.js','objects-controls.js','mobile-nav.js','finds-menus.js'))
tags = {tag for item in json.loads((ROOT / 'data/objects.json').read_text()) for tag in item.get('tags', []) + item.get('colors', [])}
core_text = ''.join(parser.text) + ''.join(value for key,value in translations.items() if key in runtime or key in tags)
authored_text = ''.join(translations.values())
OUTPUT.mkdir(exist_ok=True)
css = ['/* Generated by scripts/build-japanese-fonts.py. SIL OFL 1.1: see fonts/zen-kaku-subsets/OFL.txt.\n'
       '   Exact existing outlines, hints, metrics, weight mapping and full character coverage.\n'
       '   Canvas UI first, other authored copy on demand, rare characters in small banks. */']
report = {'faces': [], 'coreCharacters': len(set(core_text)), 'authoredCharacters': len(set(authored_text))}
retained = set()
face_rules = []
for face, weight in (('Medium','400'),('Bold','500'),('Black','600 700')):
    base = TTFont(SOURCE / f'ZenKakuGothicNew-{face}.woff2', recalcTimestamp=False)
    cmap = base.getBestCmap()
    coverage = set(cmap)
    # Keep the complete kana/voicing-mark shaping group together, including
    # decomposed dakuten/handakuten input, so normalization cannot change a face.
    core = (set(map(ord,core_text)) | set(range(0x3040,0x3100))) & coverage
    authored = (set(map(ord,authored_text)) & coverage) - core
    rare = sorted(coverage - core - authored)
    banks = [('canvas',core),('copy',authored)] + [(f'extra-{i//256:02}',set(rare[i:i+256])) for i in range(0,len(rare),256)]
    face_report = {'face': face, 'cssWeight': weight, 'originalBytes': (SOURCE / f'ZenKakuGothicNew-{face}.woff2').stat().st_size, 'originalSHA256': sha256((SOURCE / f'ZenKakuGothicNew-{face}.woff2').read_bytes()).hexdigest(), 'coverage': len(coverage), 'banks': []}
    seen = set()
    for label, points in banks:
        if not points:
            continue
        assert not seen & points
        seen |= points
        font = deepcopy(base)
        options = subset.Options()
        options.layout_features = ['*']
        options.hinting = True
        options.notdef_glyph = True
        options.notdef_outline = True
        options.name_IDs = ['*']
        options.name_languages = ['*']
        worker = subset.Subsetter(options=options)
        worker.populate(unicodes=points)
        worker.subset(font)
        font.flavor = 'woff2'
        temp = OUTPUT / f'.{face}-{label}.woff2'
        font.save(temp)
        data = temp.read_bytes()
        filename = f'zen-{face.lower()}-{label}-{sha256(data).hexdigest()[:12]}.woff2'
        target = OUTPUT / filename
        temp.replace(target)
        retained.add(filename)
        check = TTFont(target)
        reduced_cmap = check.getBestCmap()
        assert set(reduced_cmap) == points, (face,label,'coverage changed')
        # Compare every encoded character, including composite geometry, hints,
        # and horizontal/vertical metrics, after decoding the delivered WOFF2.
        for point in points:
            before, after = cmap[point], reduced_cmap[point]
            a = base['glyf'][before]
            b = check['glyf'][after]
            assert a.getCoordinates(base['glyf']) == b.getCoordinates(check['glyf']), (face,hex(point),'outline')
            assert base['hmtx'][before] == check['hmtx'][after], (face,hex(point),'horizontal metrics')
            if 'vmtx' in base:
                assert base['vmtx'][before] == check['vmtx'][after], (face,hex(point),'vertical metrics')
            before_hints = a.program.getBytecode() if hasattr(a,'program') else None
            after_hints = b.program.getBytecode() if hasattr(b,'program') else None
            assert before_hints == after_hints, (face,hex(point),'hints')
        # Include unmapped holes inside each rare bank's span to keep CSS small.
        # Core/authored characters remain excluded, so they never fetch a rare bank.
        # The font's actual cmap still supplies exactly the original coverage.
        declared = points if label in {'canvas','copy'} else set(range(min(points),max(points)+1)) - core - authored
        rule = f"@font-face{{font-family:'Zen Kaku Gothic New';font-style:normal;font-weight:{weight};font-display:swap;src:url('../fonts/zen-kaku-subsets/{filename}') format('woff2');unicode-range:{ranges(declared)}}}"
        face_rules.append((label,weight,rule))
        face_report['banks'].append({'name': label, 'file': filename, 'glyphs': len(points), 'bytes': len(data)})
    assert seen == coverage, (face,'incomplete full character coverage')
    report['faces'].append(face_report)
    print(f'{face}: canvas {face_report["banks"][0]["bytes"]:,} bytes; all {len(coverage):,} encoded characters verified.',flush=True)
for old in OUTPUT.glob('*.woff2'):
    if old.name not in retained:
        old.unlink()
(OUTPUT / 'OFL.txt').write_text((SOURCE / 'OFL.txt').read_text())
# Put equivalent ranges next to one another so gzip/Brotli can reuse them.
css.extend(rule for _,_,rule in sorted(face_rules))
(ROOT / 'css/japanese-font.css').write_text('\n'.join(css)+'\n')
(ROOT / 'data/japanese-font-build.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
print(f'{len(retained)} on-demand font banks generated; originals retained.')

# Declare the purchased Latin faces' existing coverage; never rewrite the fonts.
rules=['/* Purchased SC Walla webfonts: native Regular, Medium and Bold weights.\n   Unicode coverage is read from the unmodified originals by build-japanese-fonts.py.\n   Japanese can start loading immediately instead of waiting for a Latin font miss. */']
for face,weight in [('Regular',400),('Medium',500),('Bold',700)]:
 f=TTFont(ROOT/f'fonts/SC Walla/SCWalla-{face}.woff2')
 groups=[]
 for p in sorted(f.getBestCmap()):
  if groups and p==groups[-1][1]+1:groups[-1][1]=p
  else:groups.append([p,p])
 coverage=','.join(f'U+{a:X}' if a==b else f'U+{a:X}-{b:X}' for a,b in groups)
 rules.append(f"@font-face{{font-family:'SC Walla';src:url('../fonts/SC Walla/SCWalla-{face}.woff2') format('woff2');font-weight:{weight};font-style:normal;font-display:swap;unicode-range:{coverage}}}")
(ROOT/'css/fonts.css').write_text('\n'.join(rules)+'\n')
